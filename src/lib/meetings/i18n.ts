export function normalizeLocale(raw: unknown): LocaleId {
  const id = typeof raw === "string" ? raw.toLowerCase().split("-")[0] : "";
  return LOCALES.some((locale) => locale.id === id) ? (id as LocaleId) : "en";
}

export function systemLocale(): LocaleId {
  if (typeof navigator === "undefined") return "en";
  const tags = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of tags) {
    const id = normalizeLocale(tag);
    if (id !== "en" || String(tag || "").toLowerCase().startsWith("en")) return id;
  }
  return "en";
}

