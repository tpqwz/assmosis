export function aliasFor(programId: string, locale: string): Alias | null {
  const pack = PROGRAM_ALIASES[programId];
  if (!pack) return null;
  const id = normalizeLocale(locale);
  if (id === "en") return null;
  return pack[id] ?? null;
}

export function aliasMatches(programId: string, raw: string): boolean {
  const pack = PROGRAM_ALIASES[programId];
  if (!pack) return false;
  return Object.values(pack).some(
    (alias) => alias && (alias.short.toLowerCase() === raw || alias.name.toLowerCase() === raw),
  );
}
export function aliasHaystack(programId: string): string {
  const pack = PROGRAM_ALIASES[programId];
  if (!pack) return "";
  return Object.values(pack)
    .map((alias) => (alias ? `${alias.short} ${alias.name}` : ""))
    .join(" ");
}

export function aliasRows(): Array<{ entity: string; id: string; locale: string; short: string; name: string }> {
  const rows: Array<{ entity: string; id: string; locale: string; short: string; name: string }> = [];
  for (const [id, pack] of Object.entries(PROGRAM_ALIASES)) {
    for (const [locale, alias] of Object.entries(pack)) {
      if (!alias) continue;
      rows.push({ entity: "program", id, locale, short: alias.short, name: alias.name });
    }
  }
  return rows;
}
