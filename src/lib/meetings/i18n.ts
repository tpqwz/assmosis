export function meetingLanguage(locale: string): string {
  return MEETING_LANGUAGE[normalizeLocale(locale)] || "";
}

export function t(locale: string, key: string): string {
  const pack = COPY[normalizeLocale(locale)];
  return pack[key] || COPY.en[key] || key;
}

